import json

from usagetrim.core.diff_slimmer import slim_git_diff
from usagetrim.core.lockfile import (
    extract_lockfile_diff_delta,
    is_lockfile,
    summarize_lockfile,
)
from usagetrim.metrics.tokenizer import count_tokens


def test_is_lockfile():
    assert is_lockfile("package-lock.json")
    assert is_lockfile("/foo/bar/Cargo.lock")
    assert is_lockfile("uv.lock")
    assert is_lockfile("poetry.lock")
    assert is_lockfile("pnpm-lock.yaml")
    assert is_lockfile("yarn.lock")
    assert is_lockfile("go.sum")
    assert not is_lockfile("package.json")
    assert not is_lockfile("Cargo.toml")
    assert not is_lockfile("main.py")


def test_summarize_package_lock_json():
    npm_lock = {
        "name": "my-app",
        "version": "1.0.0",
        "lockfileVersion": 3,
        "packages": {
            "": {
                "name": "my-app",
                "version": "1.0.0",
                "dependencies": {
                    "express": "^4.19.2",
                    "zod": "^3.23.8",
                },
                "devDependencies": {
                    "typescript": "^5.4.5",
                },
            },
            "node_modules/express": {
                "version": "4.19.2",
                "resolved": "https://registry.npmjs.org/express/-/express-4.19.2.tgz",
                "integrity": "sha512-abc",
                "dependencies": {
                    "accepts": "~1.3.8",
                },
            },
            "node_modules/zod": {
                "version": "3.23.8",
                "resolved": "https://registry.npmjs.org/zod/-/zod-3.23.8.tgz",
                "integrity": "sha512-def",
            },
            "node_modules/typescript": {
                "version": "5.4.5",
                "resolved": "https://registry.npmjs.org/typescript/-/typescript-5.4.5.tgz",
                "integrity": "sha512-ghi",
            },
            "node_modules/accepts": {
                "version": "1.3.8",
                "resolved": "https://registry.npmjs.org/accepts/-/accepts-1.3.8.tgz",
                "integrity": "sha512-jkl",
            },
        },
    }
    raw = json.dumps(npm_lock, indent=2)

    # General summary
    summary = summarize_lockfile(raw, "package-lock.json")
    assert "package-lock.json" in summary
    assert "express: 4.19.2" in summary
    assert "zod: 3.23.8" in summary
    assert "typescript: 5.4.5" in summary
    assert "3 direct, 4 total packages" in summary

    # Single package query via symbol
    query_res = summarize_lockfile(raw, "package-lock.json", query_package="zod")
    assert "package 'zod'" in query_res
    assert "3.23.8" in query_res
    assert "express" not in query_res

    # Query non-existent
    not_found = summarize_lockfile(raw, "package-lock.json", query_package="nonexistent")
    assert "not found" in not_found


