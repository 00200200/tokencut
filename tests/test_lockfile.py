def test_lockfile_diff_delta():
    diff_lines = [
        "--- a/package-lock.json",
        "+++ b/package-lock.json",
        '-    "node_modules/zod": {',
        '-      "version": "3.22.0"',
        '+    "node_modules/zod": {',
        '+      "version": "3.23.8"',
        '+    "node_modules/express": {',
        '+      "version": "4.19.2"',
        '-    "node_modules/left-pad": {',
        '-      "version": "1.3.0"',
    ]
    delta = extract_lockfile_diff_delta(diff_lines, "package-lock.json")
    assert "~ zod (3.22.0 -> 3.23.8)" in delta
    assert "+ express@4.19.2" in delta
    assert "- left-pad@1.3.0" in delta


def test_slim_git_diff_with_lockfile_delta():
    raw_diff = """diff --git a/package-lock.json b/package-lock.json
index 1111..2222 100644
--- a/package-lock.json
+++ b/package-lock.json
@@ -10,6 +10,12 @@
-    "node_modules/zod": {
-      "version": "3.22.0"
+    "node_modules/zod": {
+      "version": "3.23.8"
+    "node_modules/express": {
+      "version": "4.19.2"
diff --git a/src/main.ts b/src/main.ts
index 3333..4444 100644
--- a/src/main.ts
+++ b/src/main.ts
@@ -1,3 +1,3 @@
-const a = 1;
+const a = 2;
"""
    slimmed = slim_git_diff(raw_diff)
    assert "lockfile delta:" in slimmed
    assert "~ zod (3.22.0 -> 3.23.8)" in slimmed
    assert "+ express@4.19.2" in slimmed
    assert "const a = 2;" in slimmed


def test_large_lockfile_token_reduction():
    # Simulate a 1,000 package lockfile
    pkgs = {"": {"dependencies": {f"pkg-{i}": f"1.{i}.0" for i in range(50)}}}
    for i in range(500):
        pkgs[f"node_modules/pkg-{i}"] = {
            "version": f"1.{i}.0",
            "resolved": f"https://registry.npmjs.org/pkg-{i}/-/pkg-{i}-1.{i}.0.tgz",
            "integrity": f"sha512-dummyhash{i}1234567890abcdef",
        }
    large_json = json.dumps({"packages": pkgs}, indent=2)
    raw_tokens = count_tokens(large_json).claude
    summary = summarize_lockfile(large_json, "package-lock.json")
    summary_tokens = count_tokens(summary).claude

    # Should achieve > 90% reduction
    assert summary_tokens < raw_tokens * 0.10
    assert "50 direct, 500 total packages" in summary


def test_usagetrim_read_lockfile_mcp(tmp_path):
    from usagetrim.mcp.server import handle_usagetrim_read

    lock_file = tmp_path / "package-lock.json"
    npm_lock = {
        "name": "sample",
        "lockfileVersion": 3,
        "packages": {
            "": {"dependencies": {"react": "^18.3.1"}},
            "node_modules/react": {"version": "18.3.1"},
        },
    }
    lock_file.write_text(json.dumps(npm_lock, indent=2))

    # Read without bounds should auto-summarize
    res = handle_usagetrim_read({"path": str(lock_file)})
    assert "react: 18.3.1" in res
    assert "package-lock.json" in res

    # Read with symbol
    sym_res = handle_usagetrim_read({"path": str(lock_file), "symbol": "react"})
    assert "package 'react'" in sym_res
    assert "18.3.1" in sym_res
